Prop Lookup(string name) => all.FirstOrDefault(p => p.Name == name) ?? throw new InvalidOperationException($"unknown longhand {name}");

static string B(bool b) => b ? "true" : "false";

static string Str(YamlMappingNode n, string key) => n.Children.TryGetValue(new YamlScalarNode(key), out var v) ? ((YamlScalarNode)v).Value ?? string.Empty : string.Empty;

static bool Bool(YamlMappingNode n, string key) => Str(n, key) == "true";

static string Pascal(string css)
{
    if (css.StartsWith("-gtk-", StringComparison.Ordinal))
    {
        css = css[5..];
    }

    return string.Concat(css.Split('-', StringSplitOptions.RemoveEmptyEntries).Select(w => char.ToUpperInvariant(w[0]) + w[1..]));
}

static string Camel(string s) => char.ToLowerInvariant(s[0]) + s[1..];

static string Short(Prop p)
{
    var full = Pascal(p.Name);
    if (full.StartsWith(p.Group, StringComparison.Ordinal) && full.Length > p.Group.Length && char.IsUpper(full[p.Group.Length]))
    {
        return full[p.Group.Length..];
    }

    return full;
}

static string FindRoot()
{
    var dir = Directory.GetCurrentDirectory();
    while (dir is not null && !File.Exists(Path.Combine(dir, "AvaAdwaita.slnx")))
    {
        dir = Path.GetDirectoryName(dir);
    }

    return dir ?? throw new InvalidOperationException("run inside the repository");
}

record Prop(int Id, string Name, string Kind, string Type, string Initial, bool Inherit, bool Animate, string Group, int Slot);

record Group(string Name, List<Prop> Props);

record Shorthand(string Name, string Parser, List<string> Longhands);
