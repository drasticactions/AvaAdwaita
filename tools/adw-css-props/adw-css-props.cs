#:package YamlDotNet@16.3.0
// Generates the CSS property table, ComputedStyle, the {adw:Css} path table
// and docs/css-support.md from properties.yaml.
//
//   dotnet run tools/adw-css-props/adw-css-props.cs            write the files
//   dotnet run tools/adw-css-props/adw-css-props.cs -- --check fail if a file is stale
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using YamlDotNet.RepresentationModel;

var check = args.Contains("--check");
var root = FindRoot();
var yaml = new YamlStream();
using (var reader = new StreamReader(Path.Combine(root, "tools/adw-css-props/properties.yaml")))
{
    yaml.Load(reader);
}

var doc = (YamlMappingNode)yaml.Documents[0].RootNode;
var groups = new List<Group>();
var all = new List<Prop>();
foreach (YamlMappingNode g in (YamlSequenceNode)doc["groups"])
{
    var group = new Group(Str(g, "name"), new List<Prop>());
    foreach (YamlMappingNode p in (YamlSequenceNode)g["properties"])
    {
        var prop = new Prop(all.Count, Str(p, "name"), Str(p, "kind"), Str(p, "type"), Str(p, "initial"),
            Bool(p, "inherit"), Bool(p, "animate"), group.Name, group.Props.Count);
        group.Props.Add(prop);
        all.Add(prop);
    }

    groups.Add(group);
}

var shorthands = new List<Shorthand>();
foreach (YamlMappingNode s in (YamlSequenceNode)doc["shorthands"])
{
    var longhands = ((YamlSequenceNode)s["longhands"]).Select(n => ((YamlScalarNode)n).Value!).ToList();
    shorthands.Add(new Shorthand(Str(s, "name"), Str(s, "parser"), longhands));
}

List<string> List(string key) => ((YamlSequenceNode)doc[key]).Select(n => ((YamlScalarNode)n).Value!).ToList();

var outputs = new Dictionary<string, string>
{
    ["src/AvaAdwaita.Theme/Css/Properties/CssPropertyTable.g.cs"] = PropertyTable(),
    ["src/AvaAdwaita.Theme/Css/Computed/ComputedStyle.g.cs"] = ComputedStyleCode(),
    ["src/AvaAdwaita.Theme/Markup/CssPaths.g.cs"] = PathsCode(),
    ["docs/css-support.md"] = Docs(),
};

var stale = new List<string>();
foreach (var (rel, text) in outputs)
{
    var path = Path.Combine(root, rel);
    var old = File.Exists(path) ? File.ReadAllText(path) : null;
    if (old == text)
    {
        continue;
    }

    if (check)
    {
        stale.Add(rel);
    }
    else
    {
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, text);
        Console.WriteLine($"wrote {rel}");
    }
}

if (stale.Count > 0)
{
    Console.Error.WriteLine("stale: " + string.Join(", ", stale) + " (run dotnet run tools/adw-css-props/adw-css-props.cs)");
    return 1;
}

return 0;

string PropertyTable()
{
    var sb = new StringBuilder();
    sb.AppendLine("// <auto-generated>tools/adw-css-props from properties.yaml</auto-generated>");
    sb.AppendLine("#nullable enable");
    sb.AppendLine("namespace AvaAdwaita.CssEngine.Properties;");
    sb.AppendLine();
    sb.AppendLine("internal static partial class CssPropertyTable");
    sb.AppendLine("{");
    sb.AppendLine($"    public const int Count = {all.Count};");
    sb.AppendLine();
    sb.AppendLine("    public static readonly CssProperty[] All =");
    sb.AppendLine("    [");
    foreach (var p in all)
    {
        sb.AppendLine($"        new({p.Id}, \"{p.Name}\", CssKinds.{p.Kind}, \"{p.Initial}\", inherited: {B(p.Inherit)}, animated: {B(p.Animate)}),");
    }

    sb.AppendLine("    ];");
    sb.AppendLine();
    sb.AppendLine("    public static readonly CssShorthand[] Shorthands =");
    sb.AppendLine("    [");
    foreach (var s in shorthands)
    {
        var ids = s.Longhands.Count == 1 && s.Longhands[0] == "*"
            ? "AllIds()"
            : "[" + string.Join(", ", s.Longhands.Select(l => Lookup(l).Id)) + "]";
        sb.AppendLine($"        new(\"{s.Name}\", {ids}, CssShorthandParsers.{s.Parser}),");
    }

    sb.AppendLine("    ];");
    sb.AppendLine();
    sb.AppendLine("    /// <summary>Property ids.</summary>");
    sb.AppendLine("    public static class Id");
    sb.AppendLine("    {");
    foreach (var p in all)
    {
        sb.AppendLine($"        public const int {Pascal(p.Name)} = {p.Id};");
    }

    sb.AppendLine("    }");
    sb.AppendLine("}");
    return sb.ToString();
}

string ComputedStyleCode()
{
    var sb = new StringBuilder();
    sb.AppendLine("// <auto-generated>tools/adw-css-props from properties.yaml</auto-generated>");
    sb.AppendLine("#nullable enable");
    sb.AppendLine("using System;");
    sb.AppendLine("using System.Collections.Generic;");
    sb.AppendLine("using AvaAdwaita.CssEngine.Values;");
    sb.AppendLine();
    sb.AppendLine("namespace AvaAdwaita.CssEngine.Computed;");
    sb.AppendLine();
    sb.AppendLine("public sealed partial class ComputedStyle");
    sb.AppendLine("{");
    sb.AppendLine($"    internal const int GroupCount = {groups.Count};");
    sb.AppendLine();
    foreach (var g in groups)
    {
        sb.AppendLine($"    internal {g.Name}Values {g.Name} {{ get; }}");
    }

    sb.AppendLine();
    sb.AppendLine("    internal ComputedStyle(" + string.Join(", ", groups.Select(g => $"{g.Name}Values {Camel(g.Name)}")) + ", CssCustomProperties custom)");
    sb.AppendLine("    {");
    foreach (var g in groups)
    {
        sb.AppendLine($"        {g.Name} = {Camel(g.Name)};");
    }

    sb.AppendLine("        Custom = custom;");
    sb.AppendLine("    }");
    sb.AppendLine();
    sb.AppendLine("    /// <summary>Builds a style from computed values indexed by property id, sharing equal groups with the parent.</summary>");
    sb.AppendLine("    internal static ComputedStyle Create(object?[] v, ComputedStyle? parent, CssCustomProperties custom, Dictionary<int, object>? dependents, CssStyleInterner interner)");
    sb.AppendLine("    {");
    foreach (var g in groups)
    {
        sb.AppendLine($"        var {Camel(g.Name)} = new {g.Name}Values(v);");
        sb.AppendLine($"        {Camel(g.Name)} = parent is not null && parent.{g.Name}.Equals({Camel(g.Name)}) ? parent.{g.Name} : interner.Intern({Camel(g.Name)});");
    }

    sb.AppendLine("        return interner.Intern(new ComputedStyle(" + string.Join(", ", groups.Select(g => Camel(g.Name))) + ", custom) { CurrentColorDependents = dependents });");
    sb.AppendLine("    }");
    sb.AppendLine();
    sb.AppendLine("    /// <summary>The computed value of a property, boxed.</summary>");
    sb.AppendLine("    internal object? GetValue(int id) => id switch");
    sb.AppendLine("    {");
    foreach (var p in all)
    {
        sb.AppendLine($"        {p.Id} => {p.Group}.{Short(p)},");
    }

    sb.AppendLine("        _ => throw new ArgumentOutOfRangeException(nameof(id)),");
    sb.AppendLine("    };");
    sb.AppendLine();
    sb.AppendLine("    /// <summary>Copies every computed value into <paramref name=\"v\"/>, indexed by property id.</summary>");
    sb.AppendLine("    internal void CopyTo(object?[] v)");
    sb.AppendLine("    {");
    foreach (var p in all)
    {
        sb.AppendLine($"        v[{p.Id}] = {p.Group}.{Short(p)};");
    }

    sb.AppendLine("    }");
    sb.AppendLine();
    sb.AppendLine("    private bool GroupsEqual(ComputedStyle o) =>");
    sb.AppendLine("        " + string.Join(" &&\n        ", groups.Select(g => $"ReferenceEquals({g.Name}, o.{g.Name})")) + ";");
    sb.AppendLine();
    sb.AppendLine("    private int GroupsHash()");
    sb.AppendLine("    {");
    sb.AppendLine("        var h = new HashCode();");
    foreach (var g in groups)
    {
        sb.AppendLine($"        h.Add(System.Runtime.CompilerServices.RuntimeHelpers.GetHashCode({g.Name}));");
    }

    sb.AppendLine("        return h.ToHashCode();");
    sb.AppendLine("    }");
    foreach (var g in groups)
    {
        sb.AppendLine();
        sb.AppendLine($"    /// <summary>The {g.Name} group of computed values.</summary>");
        sb.AppendLine($"    internal sealed class {g.Name}Values : IEquatable<{g.Name}Values>");
        sb.AppendLine("    {");
        sb.AppendLine($"        public {g.Name}Values(object?[] v)");
        sb.AppendLine("        {");
        foreach (var p in g.Props)
        {
            sb.AppendLine($"            {Short(p)} = ({p.Type})v[{p.Id}]!;");
        }

        sb.AppendLine("        }");
        sb.AppendLine();
        foreach (var p in g.Props)
        {
            sb.AppendLine($"        /// <summary><c>{p.Name}</c>.</summary>");
            sb.AppendLine($"        public {p.Type} {Short(p)} {{ get; }}");
            sb.AppendLine();
        }

        sb.AppendLine($"        public bool Equals({g.Name}Values? o) => o is not null && (ReferenceEquals(this, o) ||");
        sb.AppendLine("            (" + string.Join(" &&\n            ", g.Props.Select(p => $"EqualityComparer<{p.Type}>.Default.Equals({Short(p)}, o.{Short(p)})")) + "));");
        sb.AppendLine();
        sb.AppendLine($"        public override bool Equals(object? obj) => obj is {g.Name}Values o && Equals(o);");
        sb.AppendLine();
        sb.AppendLine("        public override int GetHashCode()");
        sb.AppendLine("        {");
        sb.AppendLine("            var h = new HashCode();");
        foreach (var p in g.Props)
        {
            sb.AppendLine($"            h.Add({Short(p)});");
        }

        sb.AppendLine("            return h.ToHashCode();");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
    }

    sb.AppendLine("}");
    return sb.ToString();
}

string PathsCode()
{
    var sb = new StringBuilder();
    sb.AppendLine("// <auto-generated>tools/adw-css-props from properties.yaml</auto-generated>");
    sb.AppendLine("#nullable enable");
    sb.AppendLine("using System.Collections.Generic;");
    sb.AppendLine("using AvaAdwaita.CssEngine.Values;");
    sb.AppendLine();
    sb.AppendLine("namespace AvaAdwaita.Markup;");
    sb.AppendLine();
    sb.AppendLine("internal static partial class CssPaths");
    sb.AppendLine("{");
    sb.AppendLine("    private static void AddGenerated(Dictionary<string, CssPath> d)");
    sb.AppendLine("    {");
    foreach (var p in all)
    {
        var flat = Pascal(p.Name);
        var grouped = $"{p.Group}.{Short(p)}";
        sb.AppendLine($"        d[\"{flat}\"] = new(\"{flat}\", {p.Id}, typeof({p.Type.TrimEnd('?')}), s => s.{grouped});");
        if (grouped != flat)
        {
            sb.AppendLine($"        d[\"{grouped}\"] = d[\"{flat}\"];");
        }
    }

    sb.AppendLine("    }");
    sb.AppendLine("}");
    return sb.ToString();
}

