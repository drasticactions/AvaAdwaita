namespace AvaAdwaita.Icons;

/// <summary>Which color a symbolic icon shape takes.</summary>
public enum IconRole
{
    /// <summary>Not painted.</summary>
    None,

    /// <summary>The node's <c>color</c>.</summary>
    Foreground,

    /// <summary>The palette's <c>success</c> color.</summary>
    Success,

    /// <summary>The palette's <c>warning</c> color.</summary>
    Warning,

    /// <summary>The palette's <c>error</c> color.</summary>
    Error,

    /// <summary>The palette's <c>accent</c> color.</summary>
    Accent,
}
